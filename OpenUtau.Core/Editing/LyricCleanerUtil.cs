using System; // v1.0 - 07/07/2026 - นำเข้าไลบรารีพื้นฐานสำหรับการทำงานของระบบ
using System.Collections.Generic; // v1.0 - 07/07/2026 - นำเข้าไลบรารีสำหรับการใช้งาน List เพื่อรวบรวมข้อความ
using System.IO; // v1.0 - 07/07/2026 - นำเข้าไลบรารีสำหรับการอ่านและเขียนไฟล์ข้อมูล
using System.Text; // v1.0 - 07/07/2026 - นำเข้าไลบรารีสำหรับจัดการข้อความและการเข้ารหัส (Encoding)
using System.Text.RegularExpressions; // v1.0 - 07/07/2026 - นำเข้าไลบรารี Regex สำหรับใช้คัดกรองรูปแบบตัวอักษร

namespace OpenUtau.Core.Util { // v1.0 - 07/07/2026 - กำหนดเนมสเปซให้อยู่ในกลุ่มเครื่องมือ (Utility) ของโปรเจกต์
    public static class LyricCleanerUtil { // v1.0 - 07/07/2026 - ประกาศคลาสเป็นแบบ static เพื่อให้สามารถเรียกใช้ฟังก์ชันภายในได้ทันทีโดยไม่ต้องสร้างออบเจกต์ใหม่
        
        public static string CleanLyric(string lyric) { // v1.0 - 07/07/2026 - เมธอดหลักสำหรับรับข้อความเนื้อเพลงเข้ามาทำความสะอาด
            if (string.IsNullOrEmpty(lyric)) return string.Empty; // v1.0 - 07/07/2026 - ดักจับกรณีที่เนื้อเพลงเป็นค่าว่าง เพื่อป้องกันระบบแครช

            // v1.0 - 07/07/2026 - 1. ลบสัญลักษณ์และคำที่ระบุไว้ (Whisper, Soft, Arrows, R, br)
            string[] unwanted = { "弱", "囁", "br", "BR", "R", "r", "↑", "↓", "←", "→" }; // v1.0 - 07/07/2026 - สร้างอาร์เรย์เก็บชุดคำหรือสัญลักษณ์ที่ไม่ต้องการ
            foreach (var token in unwanted) { // v1.0 - 07/07/2026 - วนลูปอ่านค่าชุดคำที่ไม่ต้องการทีละตัว
                lyric = lyric.Replace(token, ""); // v1.0 - 07/07/2026 - ค้นหาและแทนที่คำเหล่านั้นด้วยค่าว่าง (ลบออกจากเนื้อเพลง)
            }

            // v1.0 - 07/07/2026 - 2. เก็บเฉพาะตัวอักษรเนื้อเพลงหลัก (ไทย, อังกฤษ, ญี่ปุ่น) และช่องว่าง
            Regex regex = new Regex(@"([a-zA-Z\u0E00-\u0E7F\u3040-\u30FF\s]+)"); // v1.0 - 07/07/2026 - สร้างนิพจน์ปกติ (Regex) คัดเฉพาะภาษาตามช่วง Unicode ที่ต้องการ
            Match match = regex.Match(lyric); // v1.0 - 07/07/2026 - ทำการประมวลผลค้นหาข้อความที่ตรงตามเงื่อนไขจากซ้ายไปขวา

            if (match.Success) { // v1.0 - 07/07/2026 - หากพบข้อความที่ตรงตามรูปแบบ Regex ที่ตั้งไว้
                return match.Groups[1].Value.Trim(); // v1.0 - 07/07/2026 - ดึงข้อความกลุ่มแรกออกมา ตัดช่องว่างหน้า/หลังทิ้ง แล้วส่งคืนกลับไป
            }
            return lyric.Trim(); // v1.0 - 07/07/2026 - หากไม่พบรูปแบบที่ตรงกันเลย ให้ส่งคืนข้อความดั้งเดิมที่ตัดช่องว่างออกแล้ว
        }

        public static void ProcessTempFile(string filepath) { // v1.0 - 07/07/2026 - เมธอดสำหรับเปิดอ่านและเขียนทับไฟล์ชั่วคราว (จำลองมาจาก Python)
            if (!File.Exists(filepath)) return; // v1.0 - 07/07/2026 - ตรวจสอบว่ามีไฟล์อยู่จริงหรือไม่ หากไม่มีให้ออกจากการทำงานทันที

            Encoding.RegisterProvider(CodePagesEncodingProvider.Instance); // v1.0 - 07/07/2026 - ลงทะเบียน Encoding เผื่อให้ระบบรู้จักการเข้ารหัสแบบเก่า เช่น Shift-JIS
            
            string[] lines; // v1.0 - 07/07/2026 - เตรียมตัวแปรอาร์เรย์สำหรับเก็บข้อมูลแต่ละบรรทัด
            Encoding enc = Encoding.UTF8; // v1.0 - 07/07/2026 - กำหนดการเข้ารหัสเริ่มต้นเป็น UTF-8

            try { // v1.0 - 07/07/2026 - ลองอ่านไฟล์ด้วยวิธีดึงรูปแบบ UTF-8 แบบเข้มงวด
                lines = File.ReadAllLines(filepath, new UTF8Encoding(false, true)); // v1.0 - 07/07/2026 - หากไฟล์เป็น Shift-JIS คำสั่งนี้จะโยน Error (Exception) ทันที
            } catch { // v1.0 - 07/07/2026 - หากเกิดข้อผิดพลาดในการอ่านด้วย UTF-8
                enc = Encoding.GetEncoding("shift_jis"); // v1.0 - 07/07/2026 - เปลี่ยนตัวเข้ารหัสเป็น Shift-JIS สำหรับโปรแกรม/ปลั๊กอินฝั่งญี่ปุ่น
                lines = File.ReadAllLines(filepath, enc); // v1.0 - 07/07/2026 - ทำการอ่านไฟล์อีกครั้งด้วยการเข้ารหัสที่ถูกต้อง
            }

            List<string> newContent = new List<string>(); // v1.0 - 07/07/2026 - สร้าง List ไว้รวบรวมบรรทัดข้อมูลที่ผ่านการตรวจสอบแล้ว
            foreach (string line in lines) { // v1.0 - 07/07/2026 - วนลูปอ่านข้อมูลทีละบรรทัด
                if (line.StartsWith("Lyric=")) { // v1.0 - 07/07/2026 - ตรวจสอบว่าบรรทัดนี้ใช่พารามิเตอร์ของเนื้อเพลงหรือไม่
                    string[] parts = line.Split(new char[] { '=' }, 2); // v1.0 - 07/07/2026 - แบ่งข้อความออกเป็น 2 ส่วน ด้วยเครื่องหมายเท่ากับ
                    if (parts.Length == 2) { // v1.0 - 07/07/2026 - ถ้ายอดการแบ่งสำเร็จและมีเนื้อหาครบ
                        string cleanedVal = CleanLyric(parts[1]); // v1.0 - 07/07/2026 - โยนเนื้อเพลงเข้าไปในเมธอดทำความสะอาด
                        newContent.Add($"Lyric={cleanedVal}"); // v1.0 - 07/07/2026 - นำเนื้อเพลงที่คลีนแล้วประกอบกลับคืน แล้วเพิ่มลง List
                    } else { // v1.0 - 07/07/2026 - หากแยกได้ไม่สมบูรณ์
                        newContent.Add(line); // v1.0 - 07/07/2026 - ให้บันทึกบรรทัดเดิมกลับเข้าไปตามปกติ
                    }
                } else { // v1.0 - 07/07/2026 - กรณีที่เป็นค่ากำหนดอื่นๆ (เช่น NoteNum, Length)
                    newContent.Add(line); // v1.0 - 07/07/2026 - รักษาค่าเอาไว้โดยไม่แตะต้อง
                }
            }

            File.WriteAllLines(filepath, newContent, enc); // v1.0 - 07/07/2026 - ทำการเขียนชุดข้อความทั้งหมดทับกลับลงไปยังที่อยู่ไฟล์เดิม พร้อมกับ Encoding ตั้งต้น
        }
    }
